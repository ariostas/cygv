//! Tests of the phases derived from fans, against `cgv/tools/cgv_phase.py`.
//!
//! The fans are those of the vex references of the C program of PR #94 (`cgv/tests/refs_vex`):
//! every fine regular fan of two small polytopes, and both sides of the pairs of a vex phase
//! and an FRST of a different polytope with the same CY. The expected Mori cones (the wall
//! classes), grading vectors and strata are what `cgv_phase.prepare` derives from them.

use cygv::cone::facets;
use cygv::dispatch::{compute_gv_rat_nfold, compute_gv_rat_threefold, ComputeError};
use cygv::malachite::Integer;
use cygv::phase::{Fan, FanError};
use cygv::{Method, Stratum};
use nalgebra::{DMatrix, RowDVector};
use std::collections::HashMap;

/// A stratum: its three divisors and its class, as fractions.
type StratumData = ([usize; 3], &'static [(i64, i64)]);

struct Case {
    name: &'static str,
    cones: &'static [[usize; 4]],
    /// The charges, one row per Kähler parameter.
    q: &'static [&'static [i32]],
    kappa: &'static [[i32; 4]],
    mori_rays: &'static [&'static [i32]],
    grading: &'static [i32],
    strata: &'static [StratumData],
}

impl Case {
    fn fan(&self) -> Result<Fan, FanError> {
        let cones: Vec<Vec<usize>> = self.cones.iter().map(|c| c.to_vec()).collect();
        Fan::new(&cones, &columns(self.q))
    }

    fn intnums(&self) -> HashMap<(usize, usize, usize), i32> {
        self.kappa
            .iter()
            .map(|&[a, b, c, v]| ((a as usize, b as usize, c as usize), v))
            .collect()
    }
}

/// The matrix with the given columns.
fn columns(cols: &[&[i32]]) -> DMatrix<i32> {
    DMatrix::from_iterator(
        cols[0].len(),
        cols.len(),
        cols.iter().flat_map(|c| c.iter().copied()),
    )
}

