"""Writes THIRD_PARTY_LICENSES.md: the licenses of the Rust crates that the wheels and the
`cygv` executable link, which their licenses require to be distributed with them.

    python3 scripts/third_party_licenses.py          # rewrite the file
    python3 scripts/third_party_licenses.py --check  # fail if it is out of date

It reads `cargo metadata` for the locked dependency set and follows the normal dependencies
(not the build or dev ones) of the crate with the features of the wheels (`python`) and of the
executable (`cli`), for every target platform, and takes each crate's license files from its
source in the cargo registry.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")


def metadata(features: list[str]) -> dict:
    args = [
        "cargo",
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--no-default-features",
    ]
    args += ["--features", ",".join(features)]
    out = subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def linked(meta: dict) -> set[str]:
    """The ids of the packages that the root links, through normal dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen: set[str] = set()
    stack = [root]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            if (
                any(k["kind"] is None for k in dep["dep_kinds"])
                and dep["pkg"] not in seen
            ):
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    return seen


def license_texts(manifest: str) -> list[tuple[str, str]]:
    folder = Path(manifest).parent
    files = sorted(
        p
        for p in folder.iterdir()
        if p.is_file() and p.name.lower().startswith(LICENSE_PREFIXES)
    )
    return [(p.name, p.read_text(errors="replace").strip()) for p in files]


def render() -> str:
    packages: dict[str, dict] = {}
    for features in (["python"], ["cli"]):
        meta = metadata(features)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pkg_id in linked(meta):
            packages[pkg_id] = by_id[pkg_id]
    lines = [
        "# Third-party licenses",
        "",
        "The wheels of cygv and its `cygv` executable link the Rust crates below, whose",
        "licenses follow. This file is generated by `scripts/third_party_licenses.py` from",
        "`Cargo.lock`; do not edit it by hand.",
        "",
    ]
    ordered = sorted(packages.values(), key=lambda p: (p["name"], p["version"]))
    # Each distinct text once, with the crates it comes with: most are the same few texts.
    texts: dict[str, list[str]] = {}
    for p in ordered:
        label = f"{p['name']} {p['version']}"
        lines.append(f"- {label}: {p.get('license') or 'see below'}")
        found = [text for _, text in license_texts(p["manifest_path"])]
        if not found and "LGPL-3.0" in (p.get("license") or ""):
            # The LGPL is a set of permissions on top of the GPL, whose text is LICENSE.
            found = [(ROOT / "licenses" / "LGPL-3.0.txt").read_text().strip()]
        if not found:
            found = [f"(no license file shipped; the license is {p.get('license')})"]
        for text in found:
            texts.setdefault(text, []).append(label)
    for i, (text, labels) in enumerate(texts.items(), 1):
        lines += ["", f"## Text {i}", "", "Of " + ", ".join(labels) + ".", ""]
        lines += ["```text", text, "```"]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            name = Path(__file__).name
            sys.stderr.write(f"{OUTPUT.name} is out of date: run {name}\n")
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
