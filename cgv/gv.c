static int h11, ndiv, maxdeg;
static int *W, *Q, *Q0;
static int ngen_in, *gens_in;
static int nint, (*intnums)[4];
static int in_probe; /* set during the lane probe: no duplicate notes */
static int have_cones, nmhb, *mhb, ncones, *cone_n, **cone_g, (*cone_T)[2];
static int keybits;
static u128 fieldmask;

static inline int dot(const int *a, const int *b) { int s = 0; for (int t = 0; t < h11; t++) s += a[t] * b[t]; return s; }
static inline u128 pack(const int *v) {
    u128 k = 0;
    for (int t = h11 - 1; t >= 0; t--) k = (k << keybits) + (u128)(i128)v[t];
    return k;
}
static inline void unpack(u128 k, int *v) {
    for (int t = 0; t < h11; t++) {
        i64 f = (i64)(u64)(k & fieldmask);
        if (f >= ((i64)1 << (keybits - 1))) f -= (i64)1 << keybits;
        v[t] = (int)f;
        k = (k - (u128)(i128)f) >> keybits;
    }
}
static inline u64 hash128(u128 k) {
    u64 x = (u64)k ^ ((u64)(k >> 64) * 0x9E3779B97F4A7C15ull);
    x ^= x >> 31; x *= 0xD6E8FEB86659FD93ull; x ^= x >> 32;
    return x;
}

static void read_input(FILE *f) {
#define RD(x) do { if (fscanf(f, "%d", &(x)) != 1) die("bad input"); } while (0)
    RD(h11); RD(ndiv); RD(maxdeg);
    if (h11 > 64 || ndiv > 64) die("h11 or ndiv > 64 not supported");
    W = xmalloc(h11 * sizeof(int));
    for (int a = 0; a < h11; a++) RD(W[a]);
    Q = xmalloc((size_t)ndiv * h11 * sizeof(int));
    for (int i = 0; i < ndiv * h11; i++) RD(Q[i]);
    RD(ngen_in);
    gens_in = xmalloc((size_t)ngen_in * h11 * sizeof(int));
    for (int i = 0; i < ngen_in * h11; i++) RD(gens_in[i]);
    RD(nint);
    intnums = xmalloc((size_t)nint * sizeof(*intnums));
    for (int i = 0; i < nint; i++) for (int j = 0; j < 4; j++) RD(intnums[i][j]);
    int flag;
    if (fscanf(f, "%d", &flag) == 1 && flag == 1) {
        have_cones = 1;
        RD(nmhb);
        mhb = xmalloc((size_t)nmhb * h11 * sizeof(int));
        for (int i = 0; i < nmhb * h11; i++) RD(mhb[i]);
        RD(ncones);
        int with_T = ncones < 0; /* newer inputs list each cone's divisor set T */
        if (with_T) ncones = -ncones;
        cone_n = xmalloc(ncones * sizeof(int));
        cone_g = xmalloc(ncones * sizeof(int *));
        cone_T = xmalloc(ncones * sizeof(*cone_T));
        for (int c = 0; c < ncones; c++) {
            RD(cone_n[c]);
            cone_T[c][0] = cone_T[c][1] = -2; /* unknown */
            if (with_T) { RD(cone_T[c][0]); RD(cone_T[c][1]); }
            cone_g[c] = xmalloc((size_t)(cone_n[c] ? cone_n[c] : 1) * h11 * sizeof(int));
            for (int i = 0; i < cone_n[c] * h11; i++) RD(cone_g[c][i]);
        }
    }
#undef RD
    Q0 = xcalloc(h11, sizeof(int));
    for (int r = 0; r < ndiv; r++) for (int a = 0; a < h11; a++) Q0[a] += Q[r * h11 + a];
}

/* Key packing needs |coordinate| < 2^(keybits-1) for every point of degree
 * <= maxdeg. A point x = sum lambda_i g_i of the cone satisfies
 * |x_t| <= maxdeg * max_i |g_it| / deg(g_i). */
static void setup_keys(void) {
    keybits = 128 / h11;
    if (keybits > 40) keybits = 40;
    fieldmask = ((u128)1 << keybits) - 1;
    double ratio = 0;
    for (int i = 0; i < ngen_in; i++) {
        const int *g = gens_in + (size_t)i * h11;
        int d = dot(g, W);
        if (d <= 0) continue;
        for (int t = 0; t < h11; t++) { double r = (double)(g[t] < 0 ? -g[t] : g[t]) / d; if (r > ratio) ratio = r; }
    }
    double bound = ratio * maxdeg;
    if (bound >= (double)((i64)1 << (keybits - 1)) - 1) die("coordinates too large for 128-bit key packing");
}

/* ------------------------------------------------------------------------- */
/* Slot maps: u128 key -> slot, with per-slot key, degree and value          */
/* ------------------------------------------------------------------------- */
typedef struct {
    u128 *hk; int *hv; u64 mask;
    u128 *key; int *deg; Co *val; int n, cap;
} SM;
static void sm_init(SM *m, int cap) {
    u64 c = 16;
    while (c < 2 * (u64)cap) c <<= 1;
    m->hk = xmalloc(c * sizeof(u128)); m->hv = xmalloc(c * sizeof(int));
    memset(m->hv, 0xff, c * sizeof(int)); m->mask = c - 1;
    m->cap = cap > 16 ? cap : 16; m->n = 0;
    m->key = xmalloc(m->cap * sizeof(u128)); m->deg = xmalloc(m->cap * sizeof(int)); m->val = xmalloc(m->cap * sizeof(Co));
}
static void sm_free(SM *m) { free(m->hk); free(m->hv); free(m->key); free(m->deg); free(m->val); }
static inline int sm_get(const SM *m, u128 k) {
    u64 h = hash128(k) & m->mask;
    for (;;) {
        int v = m->hv[h];
        if (v < 0) return -1;
        if (m->hk[h] == k) return v;
        h = (h + 1) & m->mask;
    }
}
static void sm_rehash(SM *m) {
    u64 c = (m->mask + 1) * 2;
    free(m->hk); free(m->hv);
    m->hk = xmalloc(c * sizeof(u128)); m->hv = xmalloc(c * sizeof(int));
    memset(m->hv, 0xff, c * sizeof(int)); m->mask = c - 1;
    for (int s = 0; s < m->n; s++) {
        u64 h = hash128(m->key[s]) & m->mask;
        while (m->hv[h] >= 0) h = (h + 1) & m->mask;
        m->hk[h] = m->key[s]; m->hv[h] = s;
    }
}
/* get or create; *created set to 1 if new (value zeroed) */
static inline int sm_add(SM *m, u128 k, int deg, int *created) {
    u64 h = hash128(k) & m->mask;
    for (;;) {
        int v = m->hv[h];
        if (v < 0) break;
        if (m->hk[h] == k) { *created = 0; return v; }
        h = (h + 1) & m->mask;
    }
    if (m->n == m->cap) {
        m->cap *= 2;
        m->key = xrealloc(m->key, m->cap * sizeof(u128)); m->deg = xrealloc(m->deg, m->cap * sizeof(int)); m->val = xrealloc(m->val, m->cap * sizeof(Co));
    }
    int s = m->n++;
    m->key[s] = k; m->deg[s] = deg; m->val[s] = co_zero();
    m->hk[h] = k; m->hv[h] = s;
    *created = 1;
    if (2 * (u64)m->n > m->mask) sm_rehash(m);
    return s;
}
/* remove everything; cost proportional to the number of slots */
static void sm_clear(SM *m) {
    if ((u64)m->n * 8 > m->mask) { memset(m->hv, 0xff, (m->mask + 1) * sizeof(int)); m->n = 0; return; }
    /* locate all positions first, then blank, so probe chains stay intact */
    static __thread u64 *pos = NULL; static __thread int pcap = 0;
    if (pcap < m->n) { pcap = m->n * 2; pos = xrealloc(pos, pcap * sizeof(u64)); }
    for (int s = 0; s < m->n; s++) {
        u64 h = hash128(m->key[s]) & m->mask;
        while (m->hv[h] != s) h = (h + 1) & m->mask;
        pos[s] = h;
    }
    for (int s = 0; s < m->n; s++) m->hv[pos[s]] = -1;
    m->n = 0;
}

/* Sparse polynomial, sorted by (degree, key). */
typedef struct { int n; u128 *key; int *deg; Co *val; } SPoly;
static void sp_free(SPoly *p) { free(p->key); free(p->deg); free(p->val); memset(p, 0, sizeof(*p)); }
static void sp_alloc(SPoly *p, int n) { p->n = 0; p->key = xmalloc((n ? n : 1) * sizeof(u128)); p->deg = xmalloc((n ? n : 1) * sizeof(int)); p->val = xmalloc((n ? n : 1) * sizeof(Co)); }

/* sort slot indices by (degree, key) */
static void sort_slots(const SM *m, int *ord, int n) {
    /* insertion-merge sort on (deg, key); qsort needs a global for the map */
    if (n < 2) return;
    int *tmp = xmalloc(n * sizeof(int));
    for (int w = 1; w < n; w *= 2) {
        for (int lo = 0; lo < n; lo += 2 * w) {
            int mid = lo + w < n ? lo + w : n, hi = lo + 2 * w < n ? lo + 2 * w : n;
            int i = lo, j = mid, k = lo;
            while (i < mid && j < hi) {
                int a = ord[i], b = ord[j];
                int le = m->deg[a] < m->deg[b] || (m->deg[a] == m->deg[b] && m->key[a] <= m->key[b]);
                tmp[k++] = le ? ord[i++] : ord[j++];
            }
            while (i < mid) tmp[k++] = ord[i++];
            while (j < hi) tmp[k++] = ord[j++];
        }
        memcpy(ord, tmp, n * sizeof(int));
    }
    free(tmp);
}
/* Nonzero slots as a sorted sparse polynomial; clears the map. */
static SPoly sm_take(SM *m) {
    int *ord = xmalloc((m->n ? m->n : 1) * sizeof(int));
    int k = 0;
    for (int s = 0; s < m->n; s++) if (!co_isz(m->val[s])) ord[k++] = s;
    sort_slots(m, ord, k);
    SPoly p; sp_alloc(&p, k);
    for (int z = 0; z < k; z++) { int s = ord[z]; p.key[z] = m->key[s]; p.deg[z] = m->deg[s]; p.val[z] = m->val[s]; }
    p.n = k;
    free(ord);
    sm_clear(m);
    return p;
}

/* Binary min-heap of slots keyed by degree. */
typedef struct { int *s; int n, cap; } Heap;
static inline void hp_push(Heap *h, const int *deg, int s) {
    if (h->n == h->cap) { h->cap = h->cap ? 2 * h->cap : 256; h->s = xrealloc(h->s, h->cap * sizeof(int)); }
    int i = h->n++;
    while (i > 0) { int p = (i - 1) / 2; if (deg[h->s[p]] <= deg[s]) break; h->s[i] = h->s[p]; i = p; }
    h->s[i] = s;
}
static inline int hp_pop(Heap *h, const int *deg) {
    int top = h->s[0], last = h->s[--h->n];
    int i = 0;
    for (;;) {
        int c = 2 * i + 1;
        if (c >= h->n) break;
        if (c + 1 < h->n && deg[h->s[c + 1]] < deg[h->s[c]]) c++;
        if (deg[h->s[c]] >= deg[last]) break;
        h->s[i] = h->s[c]; i = c;
    }
    if (h->n) h->s[i] = last;
    return top;
}

